void main() {
  var pertama = 21;
  var kedua = 5;

  print(pertama + kedua); // penjumlahan

  print(pertama - kedua); // pengurangan

  print(pertama * kedua); // perkalian

  print(pertama / kedua); // pembagian double

  print(pertama ~/ kedua); // pembagian int

  print(pertama % kedua); // sisa bagi
}
