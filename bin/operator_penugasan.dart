void main() {
  var a = 10;

  a += 120; // a = a + 120

  var b = 1;
  b += 50; // b = b + 50

  print(a);
  print(b);

  var i = 1;
  i++; // i = i + 1
  print(i);

  var j = 1;
  j--; // j = j - 1
  print(j);

  var k = 1;
  k *= 5; // k = k * 5
  print(k);

  var l = 1;
  l ~/= 5; // l = l / 5
  print(l);

  var x = 1;
  ++x; // x = x + 1
  print(x);
}
